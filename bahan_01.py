import numpy as np
from google.colab import files
from tensorflow.keras.preprocessing import image

# Fungsi untuk memprediksi gambar yang diupload
def prediksi_gambar():
    uploaded = files.upload()

    for fn in uploaded.keys():
        # Memuat gambar dan meresize sesuai ukuran training (128x128)
        path = fn
        img = image.load_img(path, target_size=(128, 128))

        # Menampilkan gambar yang diupload
        plt.imshow(img)
        plt.axis('off')
        plt.show()

        # Mengubah gambar menjadi array yang bisa dibaca AI
        x = image.img_to_array(img)
        x = np.expand_dims(x, axis=0)
        x = x / 255.0 # Normalisasi sama seperti saat training

        # Proses Prediksi
        classes = model.predict(x)

        # Interpretasi hasil (karena binary, biasanya 0=Fake dan 1=Real atau sebaliknya)
        # Kita cek urutan kelasnya dulu
        if classes[0] > 0.5:
            print(f"Hasil Prediksi: REAL (Skor: {classes[0][0]:.4f})")
        else:
            print(f"Hasil Prediksi: FAKE (Skor: {classes[0][0]:.4f})")

# Jalankan fungsinya
prediksi_gambar()